def system_name() -> str:
    ext = "x86_64"
    if platform.machine() in ("armv7l", "armv8l", "aarch64", "arm64"):
        ext = "aarch64"

    return f"{platform.system().lower()}_{ext}"


@pytest.mark.boot
def test_fishtank_distribution_contains_all_expected_files(pytestconfig):
    if pytestconfig.getoption("build_target") == "emulator-linux_x64_gfxstream_internal":
        pytest.skip("Skipping fishtank distribution test for internal gfxstream build target.")

    # Determine the fishtank root directory.
    fishtank_opt = pytestconfig.getoption("fishtank")
    if not fishtank_opt:
        pytest.skip("The --fishtank option was not provided, skipping distribution check.")

    fishtank_root = Path(fishtank_opt).parents[1]
    logging.info(
        "Validating fishtank release for platform: %s, contents: %s", system_name(), fishtank_root
    )

    assert fishtank_root.exists(), f"Fishtank folder {fishtank_root} does not exist"
    assert (fishtank_root / "fishtank").exists(), f"Fishtank file /fishtank does not exist"

    expected = [
        Path(x)
        for x in EXPECTED_FISHTANK_CONTENTS.get(system_name(), [])
        if not x.endswith("/")  # We exclude directories.
    ]

    if not expected:
         pytest.skip(f"No expected fishtank contents defined for {system_name()}")

    actual = []

    for file_path in fishtank_root.rglob("*"):
        if file_path.is_file():
            rel_path = file_path.relative_to(fishtank_root)
            actual.append(rel_path)
            assert (
                rel_path in expected
            ), f"{rel_path} not found in expected fishtank contents, do you need to update the test?"

    for expected_file in expected:
        assert (
            expected_file in actual
        ), f"{expected_file} missing from fishtank distribution, do you need to update the test?"
