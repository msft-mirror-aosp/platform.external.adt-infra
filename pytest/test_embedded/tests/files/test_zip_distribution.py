def system_name() -> str:
    ext = "x86_64"
    if platform.machine() in ("armv7l", "armv8l", "aarch64", "arm64"):
        ext = "aarch64"

    return f"{platform.system().lower()}_{ext}"


@pytest.mark.boot
def test_zip_file_contains_all_expected_files(emulator: BaseEmulator):
    emu_root = Path(emulator.exe).parents[1]
    logging.info(
        "Validating release for platform: %s, contents: %s", system_name(), emu_root
    )

    assert emu_root.exists(), "Emulator folder does not exist."
    assert (emu_root / "emulator").exists(), "Emulator folder /emulator does not exist"

    expected = [
        Path(x)
        for x in EXPECTED_RELEASE_CONTENTS[system_name()]
        if not x.endswith("/")  # We exclude directories.
    ]
    actual = []

    for file_path in emu_root.rglob("*"):
        if file_path.is_file():
            rel_path = file_path.relative_to(emu_root)
            actual.append(rel_path)
            assert (
                rel_path in expected
            ), f"{rel_path} not found in expected release contents, do you need to update the test?"

    for expected_file in expected:
        assert (
            expected_file in actual
        ), f"{expected_file} missing from distribution, do you need to update the test?"
